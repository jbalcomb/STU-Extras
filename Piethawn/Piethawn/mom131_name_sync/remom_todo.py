#!/usr/bin/env python3
"""
REMOM_TODO.md: the functions ReMoM does not name yet, as a checklist, from the name map.

One item per function (a function in a file both programs link is listed once, with both ids), grouped by mom131
source file, in three parts:
  1. ReMoM has only the id comment, no code
  2. No ReMoM id at all
  3. AIL.ASM (the sound library), no ReMoM id
Ids with a reconcile 'skip' entry are left out (e.g. main: ReMoM cannot have one per program).
The companion REMOM_TODO.part{1,2,3}.agent.md files are hand-off instructions for each part.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from collections import Counter
from pathlib import Path
from typing import Dict, List, Tuple

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_MAP = Path("in/name-snapshots/mom131-remom.name-map.tsv")
DEFAULT_RECONCILE = Path("mom131_name_sync/reconcile.json")
DEFAULT_OUT = Path("REMOM_TODO.md")
AIL_FILE = "src/ail/AIL.ASM"

Entry = Tuple[str, Tuple[str, str], List[Dict]]


def skipped_ids(reconcile: Path) -> set:
    """Ids with a reconcile 'skip' entry. Powered by Claude."""
    if not reconcile.is_file():
        return set()
    entries = json.loads(reconcile.read_text(encoding="utf-8")).get("entries", {})
    return {k for k, v in entries.items() if v.get("action") == "skip"}


def gaps(rows: List[Dict], skip: set) -> Dict[str, List[Entry]]:
    """{'no-code': [...], 'no-remom': [...]}, one entry (where, (file, line), rows) per function with no ReMoM
    function; where is WZD-only, MGC-only or shared. Powered by Claude."""
    groups: Dict[Tuple[str, str], List[Dict]] = {}
    for r in rows:
        if r["id"] and r["mom131_function"]:
            groups.setdefault((r["mom131_file"], r["mom131_line"]), []).append(r)
    out: Dict[str, List[Entry]] = {"no-code": [], "no-remom": []}
    for key, g in groups.items():
        if any(r["remom_function"] for r in g) or any(r["id"] in skip for r in g):
            continue
        cat = "no-code" if any(r["remom_evidence"] == "comment" for r in g) else "no-remom"
        exes = sorted({r["exe"] for r in g}, reverse=True)
        out[cat].append(("shared" if len(exes) == 2 else exes[0] + "-only", key, g))
    return out


def item(key: Tuple[str, str], g: List[Dict], comment: bool) -> str:
    """One checklist line: our (IDA) name first; the mom131 name only for reference. Powered by Claude."""
    g = sorted(g, key=lambda r: r["exe"], reverse=True)
    ids = " · ".join(f'`{r["id"]}` {r["ida_address"]}' for r in g)
    ours = " / ".join(dict.fromkeys(r["ida_name"] for r in g if r["ida_name"])) or "(unnamed in IDA)"
    line = f'- [ ] **{ours}** — {ids} — mom131 `{g[0]["mom131_function"]}` `{key[0]}:{key[1]}`'
    if comment:
        c = [r for r in g if r["remom_evidence"] == "comment"]
        line += f' — ReMoM comment `{c[0]["remom_file"]}:{c[0]["remom_line"]}`'
    return line


def section(entries: List[Entry], comment: bool) -> List[str]:
    """Items grouped by mom131 file, in source order. Powered by Claude."""
    out: List[str] = []
    by_file: Dict[str, List[Entry]] = {}
    for e in sorted(entries, key=lambda e: (e[1][0], int(e[1][1]))):
        by_file.setdefault(e[1][0], []).append(e)
    for f, es in by_file.items():
        out += ["", f"### {f} ({len(es)})", ""]
        out += [item(k, g, comment) for _, k, g in es]
    return out


def counts(entries: List[Entry]) -> str:
    """'WZD-only n, shared n, MGC-only n'. Powered by Claude."""
    c = Counter(w for w, _, _ in entries)
    return ", ".join(f"{k} {c[k]}" for k in ("WZD-only", "shared", "MGC-only") if c[k])


def render(rows: List[Dict], skip: set, malformed: List[str] = ()) -> Tuple[str, Dict[str, int]]:
    """The markdown and the part sizes. Powered by Claude."""
    cats = gaps(rows, skip)
    ail = [e for e in cats["no-remom"] if e[1][0] == AIL_FILE]
    no_id = [e for e in cats["no-remom"] if e[1][0] != AIL_FILE]
    lines = [
        "# ReMoM TODO: functions without a ReMoM name", "",
        "Generated by `mom131_name_sync/remom_todo.py` (run by `run_mom131_name_sync.py`) from "
        "`in/name-snapshots/mom131-remom.name-map.tsv`; done items drop out on the next run.",
        "One line per function: a function in a file both programs link is listed once, with both ids.",
        "Each line: our name (IDA) — id(s) and IDA address(es) — mom131 name and source file:line, for reference "
        "— ReMoM comment location.",
        "Left out: ids with a `skip` entry in `mom131_name_sync/reconcile.json` (main).",
        "Hand-off instructions: `REMOM_TODO.part1.agent.md`, `REMOM_TODO.part2.agent.md`, `REMOM_TODO.part3.agent.md`.", "",
        f"- Part 1. ReMoM has only the id comment, no code: {len(cats['no-code'])} ({counts(cats['no-code'])})",
        f"- Part 2. No ReMoM id at all: {len(no_id)} ({counts(no_id)})",
        f"- Part 3. AIL.ASM, no ReMoM id: {len(ail)} (the sync report counts these in no-remom; listed only when the .MAP is current)", "",
        *(["**Fix first: id comments in ReMoM the tooling cannot use.** A mistyped id hides its function, so it shows up below as missing:", ""]
          + [f"- [ ] {m}" for m in malformed] + [""] if malformed else []),
        "## Part 1. ReMoM has only the id comment, no code", "",
        "Write the function under its comment.",
    ]
    lines += section(cats["no-code"], True)
    lines += ["", "## Part 2. No ReMoM id at all", "",
              "Add the function to ReMoM with its `// WZD ...` / `// MGC ...` id comment."]
    lines += section(no_id, False)
    lines += ["", "## Part 3. AIL.ASM (sound library), no ReMoM id", "",
              "Ids: WIZARDS `_AIL_` = seg037 (`// WZD s37pNN`), MAGIC `_AIL_` = seg035 (`// MGC s35pNN`)."]
    lines += section(ail, False)
    return "\n".join(lines) + "\n", {"part1": len(cats["no-code"]), "part2": len(no_id), "part3": len(ail)}


def malformed_ids(index_manifest: Path) -> List[str]:
    """Mistyped ReMoM id comments the index scan found, as 'file:line `text`'. Powered by Claude."""
    if not index_manifest.is_file():
        return []
    data = json.loads(index_manifest.read_text(encoding="utf-8"))
    return ([f"{m['file']}:{m['line']}  mistyped id `{m['text']}`" for m in data.get("malformed_ids", [])]
            + [f"{m['file']}:{m['line']}  `{m['id']}` is not directly above a function; it binds to `{m['function']}` through "
               "another tag. Remove it, or mark the area with BEGIN/END notes instead" for m in data.get("misplaced_tags", [])])


def write_todo(map_path: Path, reconcile: Path, out: Path, index_manifest: Path = None) -> Dict[str, int]:
    """Read the name map, write the checklist; returns the part sizes. Powered by Claude."""
    with map_path.open(encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f, delimiter="\t"))
    index_manifest = index_manifest or map_path.parent / "remom" / "remom_index.tsv.manifest.json"
    text, sizes = render(rows, skipped_ids(reconcile), malformed_ids(index_manifest))
    out.write_text(text, encoding="utf-8", newline="\n")
    return sizes


def main(argv=None) -> int:
    """CLI. Powered by Claude."""
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--map", type=Path, default=DEFAULT_MAP)
    p.add_argument("--reconcile", type=Path, default=DEFAULT_RECONCILE)
    p.add_argument("--out", type=Path, default=DEFAULT_OUT)
    a = p.parse_args(argv)
    sizes = write_todo(REPO_ROOT / a.map, REPO_ROOT / a.reconcile, REPO_ROOT / a.out)
    print(f"{a.out}: part 1 {sizes['part1']}, part 2 {sizes['part2']}, part 3 {sizes['part3']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
